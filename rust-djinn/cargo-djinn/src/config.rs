//! Crate configuration: `[package.metadata.djinn]` in Cargo.toml.

use std::fs;
use djinn_syntax::project::SpecFile;
use std::path::{Path, PathBuf};

#[derive(Clone)]
pub struct Config {
    pub crate_dir: PathBuf,
    /// `<crate>/djinn` by default (`[package.metadata.djinn] work_dir`): holds
    /// `solution/` (the LLM's Rust), `proofs/` (the Lean project) and `work/`
    /// (jails, jobs, backups, reports — not for version control).
    pub work_dir: PathBuf,
    /// Shared Lean package cache (Mathlib, Aeneas): `~/.cache/djinn/lake-packages`
    /// unless `lake_packages` / `DJINN_LAKE_PACKAGES` says otherwise.
    pub lake_packages: PathBuf,
    pub crate_name: String,
    /// `spec = "src/spec.rs"` or `spec = ["src/a.rs", …]`: the specification
    /// files, given by hand. Without it every `.rs` file under `src/` with a
    /// `djinn!` block is one (see `specs`).
    pub spec_manual: Option<Vec<String>>,
    pub ns: String,
    pub proofs: PathBuf,
    pub aeneas_lean: Option<String>,
    pub charon: String,
    pub aeneas: String,
    /// Path of the performance workload function inside the crate, e.g. `bench::workload`.
    pub bench: Option<String>,
    /// `bench_points = [1, 2, …]`: the workload is `pub fn workload(point: usize) -> usize`,
    /// measured once per point (a compression level, say); it returns a size to be minimised
    /// (0 if none). Without points it is `pub fn workload()`, timed alone.
    pub bench_points: Option<Vec<u64>>,
    /// The crate's `[profile.release]`, as TOML text, for the bench runner to inherit.
    pub release_profile: Option<String>,
}

impl Config {
    /// `<crate>/.djinnscratch`: everything disposable — jails, job records,
    /// backups, the bench runner, Charon/Aeneas intermediates, the agent's
    /// guide. Self-ignoring for git. `djinn/` keeps only what is committed.
    pub fn state_dir(&self) -> PathBuf {
        self.crate_dir.join(".djinnscratch")
    }
    /// The agent's guide, regenerated by every `translate`.
    pub fn guide_path(&self) -> PathBuf {
        self.state_dir().join("GUIDE.md")
    }
    /// Aeneas's `translation.json`, moved out of the Lean project after each run.
    pub fn translation_path(&self) -> PathBuf {
        self.state_dir().join("translation.json")
    }
    /// `<work_dir>/solution`: the LLM-owned implementation, included from
    /// `src/lib.rs` with `#[path = "../djinn/solution/mod.rs"] pub mod solution;`.
    pub fn solution_dir(&self) -> PathBuf {
        self.work_dir.join("solution")
    }
    /// A path inside the crate, relative to the crate directory (for texts and
    /// for mirroring the layout in a jail).
    pub fn rel(&self, p: &Path) -> String {
        p.strip_prefix(&self.crate_dir).unwrap_or(p).to_string_lossy().into_owned()
    }
    pub fn sol_rel(&self) -> String {
        self.rel(&self.solution_dir())
    }
    pub fn proofs_rel(&self) -> String {
        self.rel(&self.proofs)
    }
    pub fn lean_dir(&self) -> PathBuf {
        self.proofs.join(&self.ns)
    }
    /// The specification files, scanned afresh on each call (a file may
    /// gain or lose its `djinn!` blocks while the LSP runs).
    pub fn specs(&self) -> Vec<SpecFile> {
        djinn_syntax::project::spec_files(&self.crate_dir, self.spec_manual.as_deref())
    }
    /// The specification files' paths, for messages: `src/a.rs, src/b.rs`.
    pub fn specs_display(&self) -> String {
        let v: Vec<String> = self.specs().iter().map(|f| self.rel(&f.path)).collect();
        if v.is_empty() {
            match &self.spec_manual {
                Some(m) => m.join(", "),
                None => "src/**/*.rs".into(),
            }
        } else {
            v.join(", ")
        }
    }
    /// The specification files' texts, in the order of `specs`.
    pub fn spec_texts(&self) -> Result<Vec<(SpecFile, String)>, String> {
        self.specs().into_iter().map(|f| fs::read_to_string(&f.path).map(|t| (f.clone(), t)).map_err(|e| format!("{}: {e}", f.path.display()))).collect()
    }
    /// Is `p` one of the specification files?
    pub fn is_spec(&self, p: &Path) -> bool {
        let p = p.canonicalize().unwrap_or(p.to_path_buf());
        self.specs().iter().any(|f| f.path.canonicalize().unwrap_or(f.path.clone()) == p)
    }
    /// `NS.a.b.name`: the Lean name Aeneas gives an item of module `a::b`.
    pub fn lean_name(&self, module: Option<&str>, name: &str) -> String {
        match module {
            Some(m) => format!("{}.{}.{name}", self.ns, m.replace("::", ".")),
            None => format!("{}.{name}", self.ns),
        }
    }
    /// `crate::a::b` (Charon) — or, with the crate's name, `my_crate::a::b`
    /// (`translation.json`).
    pub fn rust_module(&self, root: &str, module: Option<&str>) -> String {
        match module {
            Some(m) => format!("{root}::{m}"),
            None => root.to_string(),
        }
    }
}

pub fn load_config(manifest: &Path) -> Result<Config, String> {
    let text = fs::read_to_string(manifest).map_err(|e| format!("{}: {e}", manifest.display()))?;
    let toml: toml::Value = toml::from_str(&text).map_err(|e| format!("{}: {e}", manifest.display()))?;
    let crate_dir = manifest
        .parent()
        .map(|p| if p.as_os_str().is_empty() { PathBuf::from(".") } else { p.to_path_buf() })
        .unwrap();
    let crate_dir = crate_dir.canonicalize().map_err(|e| format!("{}: {e}", crate_dir.display()))?;
    let crate_name = toml["package"]["name"].as_str().ok_or("package.name missing")?.to_string();
    let meta = toml
        .get("package")
        .and_then(|p| p.get("metadata"))
        .and_then(|m| m.get("djinn"))
        .cloned()
        .unwrap_or(toml::Value::Table(Default::default()));
    let get = |k: &str| meta.get(k).and_then(|v| v.as_str()).map(|s| s.to_string());
    let env = |k: &str| std::env::var(k).ok();
    // the build gate derives it the same way, to find the proofs it fingerprints
    let ns = djinn_syntax::project::namespace(get("namespace").as_deref(), &crate_name);
    if ["Sort", "Type", "Prop", "List", "Option", "Result", "Aeneas", "Std", "Lean", "Mathlib"].contains(&ns.as_str()) {
        return Err(format!("namespace `{ns}` clashes with a Lean keyword or library; set [package.metadata.djinn] namespace"));
    }
    let work_dir = crate_dir.join(get("work_dir").unwrap_or_else(|| "djinn".into()));
    let lake_packages = get("lake_packages")
        .map(|p| crate_dir.join(p))
        .or_else(|| env("DJINN_LAKE_PACKAGES").map(PathBuf::from))
        .unwrap_or_else(|| PathBuf::from(env("HOME").unwrap_or_else(|| "/tmp".into())).join(".cache").join("djinn").join("lake-packages"));
    Ok(Config {
        release_profile: toml.get("profile").and_then(|p| p.get("release")).and_then(|v| v.as_table()).map(|tab| {
            tab.iter().map(|(k, v)| format!("{k} = {v}\n")).collect::<String>()
        }),
        spec_manual: match meta.get("spec") {
            Some(toml::Value::String(p)) => Some(vec![p.clone()]),
            Some(toml::Value::Array(a)) => Some(a.iter().filter_map(|x| x.as_str().map(|s| s.to_string())).collect()),
            _ => None,
        },
        proofs: match get("proofs") {
            Some(p) => crate_dir.join(p),
            None => work_dir.join("proofs"),
        },
        work_dir,
        lake_packages,
        aeneas_lean: get("aeneas_lean").or_else(|| env("DJINN_AENEAS_LEAN")),
        charon: abs_tool(&crate_dir, get("charon").or_else(|| env("DJINN_CHARON")).unwrap_or_else(|| "charon".into())),
        aeneas: abs_tool(&crate_dir, get("aeneas").or_else(|| env("DJINN_AENEAS")).unwrap_or_else(|| "aeneas".into())),
        bench: get("bench").or_else(|| env("DJINN_BENCH")),
        bench_points: meta.get("bench_points").and_then(|v| v.as_array()).map(|a| a.iter().filter_map(|x| x.as_integer()).map(|x| x as u64).collect()),
        crate_dir,
        crate_name,
        ns,
    })
}

/// A tool path given relative to the crate directory becomes absolute; a bare
/// program name is left to `$PATH`.
fn abs_tool(crate_dir: &Path, p: String) -> String {
    if p.contains('/') && !p.starts_with('/') {
        crate_dir.join(p).to_string_lossy().into_owned()
    } else {
        p
    }
}

/// Seconds since the epoch, now.
pub fn now() -> u64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0)
}

/// `YYYY-MM-DD HH:MM:SS` in UTC.
pub fn fmt_time(secs: u64) -> String {
    let days = (secs / 86400) as i64;
    let rem = secs % 86400;
    // Howard Hinnant's civil_from_days
    let z = days + 719468;
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = z - era * 146097;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    format!("{y:04}-{m:02}-{d:02} {:02}:{:02}:{:02}", rem / 3600, (rem % 3600) / 60, rem % 60)
}

/// `YYYYmmdd-HHMMSS`, for identifiers.
pub fn id_time(secs: u64) -> String {
    fmt_time(secs).replace(['-', ':'], "").replace(' ', "-")
}
