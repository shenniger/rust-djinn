//! `cargo djinn implement`: set up a jail and run Claude Code or Codex in it,
//! in the foreground or in the background.

use crate::config::*;
use crate::status::{self, Job};
use crate::verify::{self, Log};
use std::fs;
use std::path::Path;
use std::process::{Command, Stdio};

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Agent {
    Claude,
    Codex,
}

impl Agent {
    pub fn name(self) -> &'static str {
        match self {
            Agent::Claude => "claude",
            Agent::Codex => "codex",
        }
    }
}

pub struct Opts {
    pub agent: Agent,
    pub model: Option<String>,
    /// Bypass the agent's permission system (headless-cli's default). Off by
    /// default: the jail restricts the tools instead.
    pub yolo: bool,
    pub background: bool,
    pub extra_prompt: Option<String>,
    pub max_budget_usd: Option<String>,
    pub effort: Option<String>,
    /// Extra arguments passed verbatim to the agent CLI.
    pub extra_args: Vec<String>,
    /// Harness-enforced spending limit in USD (estimated from tokens).
    pub limit_usd: Option<f64>,
    /// `-B`: discard the existing solution and proofs and start over.
    pub from_scratch: bool,
}

/// Split a `--args` string like a shell would (quotes and backslashes).
pub fn shell_words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut quote: Option<char> = None;
    let mut has = false;
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        match quote {
            Some(q) if c == q => quote = None,
            Some('"') if c == '\\' => {
                if let Some(n) = chars.next() {
                    cur.push(n);
                }
            }
            Some(_) => cur.push(c),
            None if c == '\'' || c == '"' => {
                quote = Some(c);
                has = true;
            }
            None if c == '\\' => {
                if let Some(n) = chars.next() {
                    cur.push(n);
                    has = true;
                }
            }
            None if c.is_whitespace() => {
                if has || !cur.is_empty() {
                    out.push(std::mem::take(&mut cur));
                    has = false;
                }
            }
            None => {
                cur.push(c);
                has = true;
            }
        }
    }
    if has || !cur.is_empty() {
        out.push(cur);
    }
    out
}

