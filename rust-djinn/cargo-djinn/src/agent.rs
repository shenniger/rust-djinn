fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

fn task_prompt(cfg: &Config, extra: Option<&str>, existing: Option<&str>) -> String {
    let mut p = format!(
        "You are the implementer in a Djinn-on-Aeneas project. The human has written a specification \
(`{spec}`, read-only); your job is to implement every `func` in Rust under `{sol}/` and to \
prove every obligation in `{proofs}/{ns}/Proofs.lean`, until the verifier prints PASS.\n\n\
Start by reading `GUIDE.md` (in this directory) completely: it lists the obligations, the files you may edit, \
and the Aeneas proof patterns that work.\n\n\
Rules:\n\
- Edit only `{sol}/` and `{proofs}/{ns}/Proofs.lean` (helper files may go under `{proofs}/{ns}/Proofs/`). \
Every other file is regenerated by the verifier; edits to them are discarded, and the specification \
cannot be changed.\n\
- No `unsafe`, no `sorry`, no `axiom`, no `native_decide`, no `partial`, no `implemented_by`/`extern`: the \
axiom audit rejects them.\n\
- Judge your work only with the `verify` tool (MCP server `djinn`; `./verify` from this directory does \
the same). It syncs your files into the real crate, runs the whole gate and refreshes `{proofs}/{ns}/Code/` \
with the Aeneas model of your Rust. Use `lake build` / `lake env lean {proofs}/{ns}/Proofs.lean` from \
`{proofs}/` for fast iteration between verifies.\n\
- Follow the guide's order of work: the specification-level obligations first (an ambiguous or \
contradictory specification must be reported, not implemented), then the Rust, then `verify` to obtain \
the Aeneas model, then `impl_correct`. Loop until `verify` prints PASS.\n\
- When it passes, stop and summarize what you did. If you are stuck after serious effort, stop and \
explain precisely which obligation blocks you and why.\n",
        spec = cfg.specs_display(),
        ns = cfg.ns,
        sol = cfg.sol_rel(),
        proofs = cfg.proofs_rel()
    );
    if let Some(st) = existing {
        p.push_str(&format!(
            "\nThere is existing work from earlier runs in `{}/` and `{}/` — reuse it. Keep \
everything that already passes; complete or repair only what the status below shows as missing, drafted \
or broken. If the specification changed since that work was written, some obligations may have new \
statements and new stubs were appended to `Proofs.lean` (theorems and implementations of declarations \
that no longer exist have already been archived away). Current status:\n\n",
            cfg.sol_rel(),
            cfg.proofs_rel()
        ));
        p.push_str(st);
        p.push('\n');
    }
    if let Some(e) = extra {
        p.push_str("\nAdditional instructions from the human:\n");
        p.push_str(e);
        p.push('\n');
    }
    p
}

/// Move the existing solution and proofs out of the way (`-B`).
/// Move the LLM's work (solution, Proofs.lean, helper proofs) into
/// `.djinnscratch/backup/<time>/`, leave an empty solution, and drop the
/// derived files (Aeneas model, name table, report). Used by `-B` and `clean`.
pub fn reset_work(cfg: &Config) -> Result<std::path::PathBuf, String> {
    ensure_no_running_job(cfg)?;
    let backup = cfg.state_dir().join("backup").join(id_time(now()));
    fs::create_dir_all(&backup).map_err(|e| e.to_string())?;
    let sol = cfg.solution_dir();
    if sol.exists() {
        let _ = fs::rename(&sol, backup.join("solution"));
    }
    fs::create_dir_all(&sol).map_err(|e| e.to_string())?;
    fs::write(sol.join("mod.rs"), "//! LLM-owned.\n").map_err(|e| e.to_string())?;
    let proofs = cfg.lean_dir().join("Proofs.lean");
    if proofs.exists() {
        let _ = fs::rename(&proofs, backup.join("Proofs.lean"));
    }
    let helpers = cfg.lean_dir().join("Proofs");
    if helpers.exists() {
        let _ = fs::rename(&helpers, backup.join("Proofs"));
    }
    // the optimize history (and its checkpoint) belongs to the old implementation
    let opt_log = crate::optimize::OptimizeLog::path(cfg);
    if opt_log.exists() {
        let _ = fs::rename(&opt_log, backup.join("optimize.json"));
    }
    let _ = fs::remove_dir_all(cfg.state_dir().join("optimize"));
    // the Aeneas model of the old implementation must not leak into the new run
    let _ = fs::remove_dir_all(cfg.lean_dir().join("Code"));
    let _ = fs::remove_file(cfg.translation_path());
    let _ = fs::remove_file(verify::Report::path(cfg));
    Ok(backup)
}

/// A backup directory's contents in one line.
fn describe_backup(dir: &Path) -> String {
    let fns = verify::solution_fns_in(&dir.join("solution")).len();
    let proofs = fs::read_to_string(dir.join("Proofs.lean")).map(|t| t.matches("theorem ").count()).unwrap_or(0);
    let helpers = fs::read_dir(dir.join("Proofs")).map(|r| r.count()).unwrap_or(0);
    format!("{fns} implemented function(s), {proofs} theorem(s){}", if helpers > 0 { format!(", {helpers} helper file(s)") } else { String::new() })
}

pub fn backups(cfg: &Config) -> Vec<std::path::PathBuf> {
    let mut v: Vec<std::path::PathBuf> = fs::read_dir(cfg.state_dir().join("backup")).into_iter().flatten().flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect();
    v.sort();
    v
}

/// `cargo djinn clean --list`.
pub fn list_backups(cfg: &Config) -> Result<(), String> {
    let b = backups(cfg);
    if b.is_empty() {
        eprintln!("no backups in {}", cfg.rel(&cfg.state_dir().join("backup")));
        return Ok(());
    }
    for d in &b {
        eprintln!("  {}  {}", d.file_name().unwrap().to_string_lossy(), describe_backup(d));
    }
    eprintln!("restore one with `cargo djinn clean --restore <ID>` (the latest without an ID)");
    Ok(())
}

/// `cargo djinn clean --restore [ID]`: bring a backup (written by `clean` or
/// by `-B`) back as the crate's solution and proofs, then verify. Work present
/// in the crate is archived first, so nothing is lost by restoring.
pub fn restore(cfg: &Config, id: Option<&str>) -> Result<bool, String> {
    ensure_no_running_job(cfg)?;
    let all = backups(cfg);
    let src = match id {
        Some(id) => all.iter().find(|p| p.file_name().map(|n| n == id).unwrap_or(false)).cloned().ok_or_else(|| format!("no backup `{id}`; `cargo djinn clean --list` shows them"))?,
        None => all.last().cloned().ok_or("no backups to restore")?,
    };
    let name = src.file_name().unwrap().to_string_lossy().into_owned();
    // current work, if any, goes to a backup of its own (reset_work also drops the derived files)
    let has_work = !verify::solution_fns(cfg).is_empty()
        || fs::read_to_string(cfg.lean_dir().join("Proofs.lean")).map(|t| t.matches("theorem ").count() > t.matches(":= by\n  sorry").count()).unwrap_or(false);
    if has_work {
        let b = reset_work(cfg)?;
        eprintln!("current solution and proofs archived to {}", b.display());
    } else {
        let _ = fs::remove_dir_all(cfg.lean_dir().join("Code"));
        let _ = fs::remove_file(cfg.translation_path());
    }
    // the backup's files, into place
    if src.join("solution").is_dir() {
        let _ = fs::remove_dir_all(cfg.solution_dir());
        copy_tree(&src.join("solution"), &cfg.solution_dir())?;
    }
    verify::translate(cfg, &mut Log::new(false))?; // Spec/Obligations/Audit and the lakefile, if missing
    if src.join("Proofs.lean").exists() {
        fs::copy(src.join("Proofs.lean"), cfg.lean_dir().join("Proofs.lean")).map_err(|e| e.to_string())?;
    }
    if src.join("Proofs").is_dir() {
        let _ = fs::remove_dir_all(cfg.lean_dir().join("Proofs"));
        copy_tree(&src.join("Proofs"), &cfg.lean_dir().join("Proofs"))?;
    }
    // its optimize history, which a later `optimize` resumes
    if src.join("optimize.json").exists() {
        let _ = fs::copy(src.join("optimize.json"), crate::optimize::OptimizeLog::path(cfg));
    }
    eprintln!("restored backup {name} ({}); verifying", describe_backup(&src));
    let r = verify::verify(cfg, None, &mut Log::new(true));
    eprintln!("{}", r.summary());
    Ok(r.pass)
}

fn copy_tree(src: &Path, dst: &Path) -> Result<(), String> {
    fs::create_dir_all(dst).map_err(|e| format!("{}: {e}", dst.display()))?;
    for e in fs::read_dir(src).map_err(|e| format!("{}: {e}", src.display()))?.flatten() {
        let p = e.path();
        let d = dst.join(e.file_name());
        if p.is_dir() {
            copy_tree(&p, &d)?;
        } else {
            fs::copy(&p, &d).map_err(|e| format!("{}: {e}", p.display()))?;
        }
    }
    Ok(())
}

/// `cargo djinn clean`: archive the implementation and proofs in the backup
/// directory and remove everything derived from them, so the crate is back to
/// "never attempted" (the next `cargo build` says so; `implement` starts over).
/// Jobs, jails and earlier backups are kept.
pub fn clean(cfg: &Config) -> Result<(), String> {
    let had_solution = verify::solution_fns(cfg).len();
    let had_proofs = cfg.lean_dir().join("Proofs.lean").exists();
    let backup = reset_work(cfg)?;
    // the regenerated Lean (Spec, Obligations, Audit, Code) and the build cache of this project
    let _ = fs::remove_dir_all(cfg.lean_dir());
    let _ = fs::remove_dir_all(cfg.proofs.join(".lake").join("build"));
    let _ = fs::remove_file(cfg.state_dir().join(format!("{}.llbc", cfg.crate_name)));
    let _ = fs::remove_file(verify::Report::log_path(cfg));
    let _ = fs::remove_dir_all(cfg.state_dir().join("bench"));
    eprintln!(
        "archived {} implemented function(s) and {} to {}",
        had_solution,
        if had_proofs { "the proofs" } else { "no proofs" },
        backup.display()
    );
    eprintln!("removed the generated Lean ({}), the Aeneas model, the report and the build cache", cfg.rel(&cfg.lean_dir()));
    eprintln!("restore: copy `solution/` and `Proofs.lean` back from the backup and run `cargo djinn verify`");
    Ok(())
}

/// The wrapper script of a run: records start/end and the agent's exit code.
/// With `DJINN_DRIVER_PID` set in the environment (foreground runs), a
/// watchdog kills the whole process group as soon as the driver is gone, so
/// an agent never outlives a driver that died by SIGKILL, SIGHUP or a crash;
/// background runs and manual `bash run.sh` re-runs have no driver to watch.
fn run_script(jail: &Path, argv: &[String], log: &Path) -> String {
    format!(
        "#!/bin/bash\n# how the agent was invoked; re-run with `bash run.sh`\ncd {jail}\n\
if [ -n \"$DJINN_DRIVER_PID\" ]; then\n\
  ( while kill -0 \"$DJINN_DRIVER_PID\" 2>/dev/null; do sleep 2; done; echo driver-died > exit-code; date +%s > ended; kill -TERM -$$ 2>/dev/null; sleep 2; kill -KILL -$$ 2>/dev/null ) &\n\
  WATCHDOG=$!\n\
fi\n\
date +%s > started\n{cmd} < PROMPT.md 2>&1 | tee -a {log}\necho \"${{PIPESTATUS[0]}}\" > exit-code\ndate +%s > ended\n\
[ -n \"$WATCHDOG\" ] && kill \"$WATCHDOG\" 2>/dev/null\nexit 0\n",
        jail = sh_quote(&jail.to_string_lossy()),
        cmd = argv.iter().map(|a| sh_quote(a)).collect::<Vec<_>>().join(" "),
        log = sh_quote(&log.to_string_lossy())
    )
}

/// Stop a run's process group: TERM, a grace period, KILL; record the outcome.
fn kill_run(pid: u32, jail: &Path, why: &str) {
    let _ = Command::new("kill").args(["-TERM", &format!("-{pid}")]).output();
    std::thread::sleep(std::time::Duration::from_secs(2));
    let _ = Command::new("kill").args(["-KILL", &format!("-{pid}")]).output();
    let _ = fs::write(jail.join("exit-code"), format!("{why}\n"));
    let _ = fs::write(jail.join("ended"), format!("{}\n", now()));
}

fn agent_argv(opts: &Opts, jail: &Path, bin: &Path, manifest: &Path) -> Vec<String> {
    let s = |x: &str| x.to_string();
    match opts.agent {
        Agent::Claude => {
            let mut a = vec![
                s("claude"),
                s("-p"),
                s("--verbose"),
                s("--output-format"),
                s("stream-json"),
                s("--mcp-config"),
                s(".mcp.json"),
                s("--strict-mcp-config"),
                s("--permission-prompts"),
                s("none"),
            ];
            if opts.yolo {
                a.push(s("--dangerously-skip-permissions"));
            } else {
                a.extend([s("--permission-mode"), s("acceptEdits"), s("--allowedTools")]);
                a.extend(ALLOWED_TOOLS.iter().map(|t| s(t)));
                // the jail scripts, when the agent spells them with an absolute path
                for sc in ["verify", "status", "bench"] {
                    a.push(format!("Bash({}/{sc}*)", jail.display()));
                }
            }
            if let Some(m) = &opts.model {
                a.extend([s("--model"), m.clone()]);
            }
            if let Some(b) = &opts.max_budget_usd {
                a.extend([s("--max-budget-usd"), b.clone()]);
            }
            if let Some(e) = &opts.effort {
                a.extend([s("--effort"), e.clone()]);
            }
            if opts.max_budget_usd.is_none() {
                if let Some(l) = opts.limit_usd {
                    a.extend([s("--max-budget-usd"), format!("{l}")]);
                }
            }
            a.extend(opts.extra_args.iter().cloned());
            a
        }
        Agent::Codex => {
            let mut a = vec![
                s("codex"),
                s("exec"),
                s("-C"),
                jail.to_string_lossy().into_owned(),
                s("--skip-git-repo-check"),
                s("--json"),
                s("-o"),
                jail.join("last-message.txt").to_string_lossy().into_owned(),
                s("-c"),
                format!("mcp_servers.djinn.command={}", toml_str(&bin.to_string_lossy())),
                s("-c"),
                format!(
                    "mcp_servers.djinn.args=[{},{},{},{},{}]",
                    toml_str("mcp"),
                    toml_str("--jail"),
                    toml_str(&jail.to_string_lossy()),
                    toml_str("--manifest-path"),
                    toml_str(&manifest.to_string_lossy())
                ),
                s("-c"),
                s("approval_policy=\"never\""),
                s("-c"),
                s("mcp_servers.djinn.default_tools_approval_mode=\"auto\""),
                // a verify runs Charon, Aeneas and lake: well over Codex's default tool timeout
                s("-c"),
                s("mcp_servers.djinn.tool_timeout_sec=1800"),
            ];
            if opts.yolo {
                a.push(s("--dangerously-bypass-approvals-and-sandbox"));
            } else {
                a.extend([s("--sandbox"), s("workspace-write")]);
            }
            if let Some(m) = &opts.model {
                a.extend([s("-m"), m.clone()]);
            }
            if let Some(e) = &opts.effort {
                a.extend([s("-c"), format!("model_reasoning_effort={}", toml_str(e))]);
            }
            a.extend(opts.extra_args.iter().cloned());
            a.push(s("-"));
            a
        }
    }
}

fn toml_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Refuse to start a second agent on the same crate: every `verify` from a
/// jail syncs that jail's files into the real crate, so two agents would
/// overwrite each other's work (and `-B` would move a running agent's
/// results away).
pub fn ensure_no_running_job(cfg: &Config) -> Result<(), String> {
    for j in status::load_jobs(cfg) {
        if matches!(status::job_state(&j), status::JobState::Running) {
            return Err(format!(
                "job {} ({}) is still running on this crate (pid {}); wait for it, or stop it with `kill -TERM -{}`",
                j.id, j.agent, j.pid, j.pid
            ));
        }
    }
    Ok(())
}

pub fn implement(cfg: &Config, opts: Opts, bin: &Path) -> Result<bool, String> {
    ensure_no_running_job(cfg)?;
    if opts.from_scratch {
        let backup = reset_work(cfg)?;
        eprintln!("-B: previous solution and proofs moved to {}", backup.display());
    }
    // make sure the trusted side is current (merging stubs for new
    // obligations into an existing Proofs.lean), and try to populate Code/
    let mut log = Log::new(true);
    verify::translate(cfg, &mut log)?;
    // existing work: an implemented function, or a proof that is more than the
    // skeleton's `sorry` (the skeleton itself always exists after `translate`)
    let proofs_text = fs::read_to_string(cfg.lean_dir().join("Proofs.lean")).unwrap_or_default();
    let proofs_started = proofs_text.matches("theorem ").count() > proofs_text.matches(":= by\n  sorry").count();
    let had_work = !opts.from_scratch && (verify::solution_fns(cfg).len() > 0 || proofs_started);
    let mut existing_status = None;
    if cfg.solution_dir().exists() {
        eprintln!("== initial verify (to populate the Aeneas model, if the solution builds)");
        let r = verify::verify(cfg, None, &mut Log::new(false));
        // a PASS of the specification alone is no reason to stop: `fn`s without
        // an implementation have no `impl_correct` obligation yet
        let missing = r.unimplemented();
        eprintln!(
            "initial state: {}",
            match (r.pass, missing.is_empty()) {
                (true, true) => "PASS already".to_string(),
                (true, false) => format!("specification verified; not implemented yet: {}", missing.join(", ")),
                _ => format!("FAIL at {}", r.stage),
            }
        );
        if r.pass && missing.is_empty() {
            eprintln!("nothing to do: every function is implemented and every obligation verified (use -B to reimplement from scratch)");
            return Ok(true);
        }
    }
    if had_work {
        let v = status::views(cfg, verify::Report::load(cfg).as_ref(), Some((&cfg.solution_dir(), &cfg.proofs)));
        existing_status = Some(status::render(&v));
        eprintln!("existing work found; the agent is asked to reuse it:\n{}", existing_status.as_ref().unwrap());
    }
    for j in status::load_jobs(cfg) {
        if matches!(status::job_state(&j), status::JobState::Running) {
            eprintln!("warning: job {} ({}) is still running; two agents would race on the solution directory and Proofs.lean", j.id, j.agent);
        }
    }
    let started = now();
    let id = format!("{}-{}", id_time(started), opts.agent.name());
    let jail = crate::jail::create(cfg, &id, bin)?;
    let prompt = task_prompt(cfg, opts.extra_prompt.as_deref(), existing_status.as_deref());
    fs::write(jail.join("PROMPT.md"), &prompt).map_err(|e| e.to_string())?;
    let argv = agent_argv(&opts, &jail, bin, &cfg.crate_dir.join("Cargo.toml"));
    let log_path = jail.join("agent.log");
    let script = run_script(&jail, &argv, &log_path);
    fs::write(jail.join("run.sh"), &script).map_err(|e| e.to_string())?;
    eprintln!("jail: {}", jail.display());
    eprintln!("agent: {}", argv.join(" "));

    let mut cmd = Command::new("bash");
    cmd.arg(jail.join("run.sh")).current_dir(&jail);
    if opts.background {
        use std::os::unix::process::CommandExt;
        cmd.stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null());
        cmd.process_group(0);
        let child = cmd.spawn().map_err(|e| format!("cannot start {}: {e}", opts.agent.name()))?;
        let job = Job { id: id.clone(), agent: opts.agent.name().into(), pid: child.id(), started, jail: jail.clone(), log: log_path, background: true, model: opts.model.clone(), limit_usd: opts.limit_usd };
        status::save_job(cfg, &job)?;
        if opts.limit_usd.is_some() {
            // a detached supervisor enforces the limit
            let mut sup = Command::new(bin);
            sup.args(["supervise", "--job", &id, "--manifest-path"]).arg(cfg.crate_dir.join("Cargo.toml"));
            sup.stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null());
            sup.process_group(0);
            sup.spawn().map_err(|e| format!("cannot start the supervisor: {e}"))?;
        }
        eprintln!("started background job {id} (pid {}). Follow with `cargo djinn status`; log: {}", child.id(), job.log.display());
        Ok(true)
    } else {
        use std::os::unix::process::CommandExt;
        cmd.process_group(0);
        cmd.env("DJINN_DRIVER_PID", std::process::id().to_string());
        // the raw agent stream goes to agent.log only; we print progress reports
        cmd.stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null());
        let child = cmd.spawn().map_err(|e| format!("cannot start {}: {e}", opts.agent.name()))?;
        let job = Job { id: id.clone(), agent: opts.agent.name().into(), pid: child.id(), started, jail: jail.clone(), log: log_path.clone(), background: false, model: opts.model.clone(), limit_usd: opts.limit_usd };
        status::save_job(cfg, &job)?;
        let done = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
        let sup = {
            let job = job.clone();
            let done = done.clone();
            std::thread::spawn(move || supervise(&job, Some(done)))
        };
        let mon = {
            let cfg = cfg.clone();
            let job = job.clone();
            let done = done.clone();
            std::thread::spawn(move || monitor(&cfg, &job, done))
        };
        eprintln!("agent running; progress reports follow (raw stream in {})", log_path.display());
        // Ctrl-C: the agent is in its own process group (so the terminal's
        // SIGINT does not reach it); stop it ourselves, then leave
        let stop = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
        {
            let stop = stop.clone();
            let _ = ctrlc::set_handler(move || stop.store(true, std::sync::atomic::Ordering::SeqCst));
        }
        let mut child = child;
        let st = loop {
            if stop.load(std::sync::atomic::Ordering::SeqCst) {
                eprintln!("\ninterrupted: stopping the agent (pid {})", child.id());
                kill_run(child.id(), &jail, "interrupted");
                let _ = child.wait();
                done.store(true, std::sync::atomic::Ordering::SeqCst);
                let _ = sup.join();
                let _ = mon.join();
                let u = status::summarize_log(&log_path, job.model.as_deref());
                eprintln!("agent stopped; {}", u.line());
                eprintln!("its last synced work (if any) is in the crate; `cargo djinn status` shows it, `cargo djinn verify` judges it");
                return Err("interrupted".into());
            }
            match child.try_wait() {
                Ok(Some(st)) => break st,
                Ok(None) => std::thread::sleep(std::time::Duration::from_millis(300)),
                Err(e) => return Err(e.to_string()),
            }
        };
        done.store(true, std::sync::atomic::Ordering::SeqCst);
        let _ = sup.join();
        let _ = mon.join();
        // the agent's last verify already synced its files and wrote the report;
        // if that was a PASS after the job started, do not spend another run
        let fresh_pass = verify::Report::load(cfg).map(|r| r.pass && r.unimplemented().is_empty() && r.time >= started).unwrap_or(false);
        let r = if fresh_pass {
            eprintln!("\n== agent exited ({st}); its last verify already PASSED");
            verify::Report::load(cfg).unwrap()
        } else {
            eprintln!("\n== agent exited ({st}); final verify");
            verify::verify(cfg, Some(&jail), &mut Log::new(true))
        };
        let u = status::summarize_log(&log_path, job.model.as_deref());
        let el = status::job_elapsed(&job);
        eprintln!("\n{}", r.summary());
        eprintln!("agent time {}m{:02}s; {}", el / 60, el % 60, u.line());
        if fs::read_to_string(jail.join("exit-code")).map(|t| t.trim() == "limit").unwrap_or(false) {
            eprintln!("the agent was stopped by the spending limit");
        }
        if let Some(e) = &u.api_error {
            eprintln!("the agent stopped on an API error: {e}");
        }
        if !u.last_message.is_empty() {
            eprintln!("agent's last message:\n{}", u.last_message);
        }
        Ok(r.pass && r.unimplemented().is_empty())
    }
}

/// Poll the agent's log and stop its process group when the estimated spend
/// reaches the limit. Returns when the agent has exited.
pub fn supervise(job: &Job, done: Option<std::sync::Arc<std::sync::atomic::AtomicBool>>) {
    let Some(limit) = job.limit_usd else { return };
    loop {
        for _ in 0..5 {
            if done.as_ref().map(|d| d.load(std::sync::atomic::Ordering::SeqCst)).unwrap_or(false) {
                return;
            }
            std::thread::sleep(std::time::Duration::from_secs(1));
        }
        if job.jail.join("exit-code").exists() {
            return;
        }
        let alive = Command::new("kill").args(["-0", &job.pid.to_string()]).output().map(|o| o.status.success()).unwrap_or(false);
        if !alive {
            return;
        }
        let u = status::summarize_log(&job.log, job.model.as_deref());
        let cost = u.cost_usd.or(u.est_cost_usd).unwrap_or(0.0);
        if cost >= limit {
            let _ = Command::new("kill").args(["-TERM", &format!("-{}", job.pid)]).output();
            std::thread::sleep(std::time::Duration::from_secs(3));
            let _ = Command::new("kill").args(["-KILL", &format!("-{}", job.pid)]).output();
            let _ = fs::write(job.jail.join("exit-code"), "limit\n");
            let _ = fs::write(job.jail.join("ended"), format!("{}\n", now()));
            return;
        }
    }
}

/// Foreground progress reports: every `period` seconds, snapshot the jail
/// (solution functions + a type-check of Proofs.lean), diff against the
/// previous snapshot, and print what changed; also report verifier runs and
/// the agent's messages.
fn monitor(cfg: &Config, job: &Job, done: std::sync::Arc<std::sync::atomic::AtomicBool>) {
    use std::sync::atomic::Ordering;
    let period = 20u64;
    let t0 = std::time::Instant::now();
    let stamp = || {
        let e = t0.elapsed().as_secs();
        format!("[{:02}:{:02}]", e / 60, e % 60)
    };
    let mut prev: Vec<status::DeclView> = Vec::new();
    let mut last_report_time = verify::Report::load(cfg).map(|r| r.time).unwrap_or(0);
    let mut verifies = 0usize;
    let mut last_msg = String::new();
    let mut first = true;
    loop {
        // sleep in small steps so we notice completion quickly
        for _ in 0..period {
            if done.load(Ordering::SeqCst) {
                break;
            }
            std::thread::sleep(std::time::Duration::from_secs(1));
        }
        let finished = done.load(Ordering::SeqCst);
        // the agent's messages
        let u = status::summarize_log(&job.log, job.model.as_deref());
        if !u.last_message.is_empty() && u.last_message != last_msg {
            let one: String = u.last_message.lines().collect::<Vec<_>>().join(" ");
            let short: String = one.chars().take(300).collect();
            eprintln!("{} agent: {short}{}", stamp(), if one.chars().count() > 300 { "…" } else { "" });
            last_msg = u.last_message.clone();
        }
        // verifier runs
        if let Some(r) = verify::Report::load(cfg) {
            if r.time > last_report_time {
                last_report_time = r.time;
                verifies += 1;
                let proved = r.obligations.values().filter(|v| v.as_str() == "proved").count();
                eprintln!(
                    "{} verify #{verifies}: {} ({} s) — {proved}/{} obligations proved",
                    stamp(),
                    if r.pass { "PASS".to_string() } else { format!("FAIL at {}", r.stage) },
                    r.duration_secs,
                    r.obligations.len()
                );
                for e in r.errors.iter().take(3) {
                    eprintln!("{}   {e}", stamp());
                }
            }
        }
        if finished {
            // no further snapshot: a type-check of a large Proofs.lean takes up
            // to a minute, and the final verify (or the fresh PASS) follows anyway
            break;
        }
        // the work in the jail
        let report = verify::Report::load(cfg);
        let cur = status::views(cfg, report.as_ref(), Some((&crate::jail::sol_in(cfg, &job.jail), &crate::jail::proofs_in(cfg, &job.jail))));
        if first {
            first = false;
        } else {
            for line in status::diff_views(&prev, &cur) {
                eprintln!("{} {line}", stamp());
            }
        }
        prev = cur;
    }
    let u = status::summarize_log(&job.log, job.model.as_deref());
    eprintln!("{} agent exited{}; {}", stamp(), if u.ended_turn { "" } else { " WITHOUT finishing its turn (signal, crash or CLI error)" }, u.line());
}

/// Outcome of one foreground agent run.
pub struct AgentRun {
    pub job: Job,
    pub exit_ok: bool,
    pub interrupted: bool,
    pub usage: status::Usage,
}

/// Run an agent in a fresh jail with `prompt`, in the foreground, printing
/// progress reports. `stop` is polled; when it is set (Ctrl-C), the agent's
/// process group is killed and `interrupted` is reported. Unlike
/// `implement`, nothing is verified or synced afterwards: the caller decides.
pub fn run_foreground(cfg: &Config, opts: &Opts, prompt: &str, bin: &Path, stop: &std::sync::atomic::AtomicBool, label: &str) -> Result<AgentRun, String> {
    use std::os::unix::process::CommandExt;
    use std::sync::atomic::Ordering;
    let started = now();
    let id = format!("{}-{}-{}", id_time(started), label, opts.agent.name());
    let jail = crate::jail::create(cfg, &id, bin)?;
    fs::write(jail.join("PROMPT.md"), prompt).map_err(|e| e.to_string())?;
    let argv = agent_argv(opts, &jail, bin, &cfg.crate_dir.join("Cargo.toml"));
    let log_path = jail.join("agent.log");
    let script = run_script(&jail, &argv, &log_path);
    fs::write(jail.join("run.sh"), &script).map_err(|e| e.to_string())?;
    eprintln!("jail: {}", jail.display());
    let mut cmd = Command::new("bash");
    cmd.arg(jail.join("run.sh")).current_dir(&jail);
    cmd.process_group(0);
    cmd.env("DJINN_DRIVER_PID", std::process::id().to_string());
    cmd.stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null());
    let mut child = cmd.spawn().map_err(|e| format!("cannot start {}: {e}", opts.agent.name()))?;
    let job = Job { id: id.clone(), agent: opts.agent.name().into(), pid: child.id(), started, jail: jail.clone(), log: log_path.clone(), background: false, model: opts.model.clone(), limit_usd: opts.limit_usd };
    status::save_job(cfg, &job)?;
    let done = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
    let sup = {
        let job = job.clone();
        let done = done.clone();
        std::thread::spawn(move || supervise(&job, Some(done)))
    };
    let mon = {
        let cfg = cfg.clone();
        let job = job.clone();
        let done = done.clone();
        std::thread::spawn(move || monitor(&cfg, &job, done))
    };
    let mut interrupted = false;
    let exit_ok = loop {
        if stop.load(Ordering::SeqCst) {
            eprintln!("\ninterrupted: stopping the agent (pid {})", child.id());
            kill_run(child.id(), &jail, "interrupted");
            let _ = child.wait();
            interrupted = true;
            break false;
        }
        match child.try_wait() {
            // run.sh always exits 0: the agent's own status is in `exit-code`
            Ok(Some(_)) => break fs::read_to_string(jail.join("exit-code")).map(|t| t.trim() == "0").unwrap_or(false),
            Ok(None) => std::thread::sleep(std::time::Duration::from_millis(300)),
            Err(e) => return Err(e.to_string()),
        }
    };
    done.store(true, Ordering::SeqCst);
    let _ = sup.join();
    let _ = mon.join();
    let usage = status::summarize_log(&log_path, job.model.as_deref());
    Ok(AgentRun { job, exit_ok, interrupted, usage })
}
