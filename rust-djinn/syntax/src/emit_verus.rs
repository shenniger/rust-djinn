//! Rendering the Verus project's trusted files from lowered declarations:
//! `relations.rs` (the `_pre`/`_spec` functions), `obligations.rs` (the
//! pinned proof obligations), the implementation stubs of the mirrored
//! specification modules, the `proofs.rs` skeleton and `vocab.rs`.
//!
//! How an obligation is pinned without a kernel: every obligation is a
//! trusted function with the pinned contract whose body only *calls* the
//! implementer's function of the same name — a `proof fn` of `proofs.rs`
//! for the proof obligations, the solution's `fn` for `impl_correct`. Verus
//! checks the call: the callee's `requires` must follow from the pinned
//! `requires`, and the pinned `ensures` from the callee's `ensures`. The
//! implementer may state its own function however it likes; what is proved
//! is what the trusted file says.
//!
//! The pinned `ensures` of a proof obligation is one term, `f_wf_post(params)`,
//! an `open spec fn` of `relations.rs` whose body is the obligation's
//! conjunction (`Obligation::post_fn`). The skeleton's stub states the same
//! term, so the transfer from the implementer's function to the wrapper is
//! syntactic — a long statement (nested quantifiers, many items) costs the
//! wrapper nothing; an implementer who states the expanded conjunction
//! instead still verifies, the wrapper then unfolding the definition.

use crate::ast::*;
use crate::lower::Lowered;
use crate::lower_verus::{eq_fn_name, eq_term, exec_type, needs_eq_with, quant, verus_ident, view_term, view_type};
use crate::types::TypeNames;
use std::collections::HashMap;

pub struct EmitCx<'a> {
    /// Rust type name → its path in the verification crate
    /// (`crate::spec::Token`); `const:K` → the table's path.
    pub names: &'a TypeNames,
    /// Rust function name → the path of its contract-carrying stub
    /// (`crate::spec::f`), for the implemented functions only.
    pub impl_names: &'a HashMap<String, String>,
}

/// The marker left in a stub's body by the skeleton; a stub still holding it
/// has not been worked on.
pub const TODO: &str = "// TODO(implementer): prove this (replace this comment; an obligation that already verifies needs nothing more)";

/// `name: Type` binders.
fn binders(vars: &[(String, RType)], names: &TypeNames) -> Vec<String> {
    vars.iter().map(|(n, t)| format!("{}: {}", verus_ident(n), view_type(t, names))).collect()
}

fn arg_names(vars: &[(String, RType)]) -> Vec<String> {
    vars.iter().map(|(n, _)| verus_ident(n)).collect()
}

fn choice_binders(choices: &[(String, String)]) -> Vec<String> {
    choices.iter().map(|(n, t)| format!("{n}: {t}")).collect()
}

fn choice_names(choices: &[(String, String)]) -> Vec<String> {
    choices.iter().map(|(n, _)| n.clone()).collect()
}

fn conj_lines(ps: &[String]) -> String {
    if ps.is_empty() {
        "true".into()
    } else {
        ps.join(" &&\n    ")
    }
}

const HEADER: &str = "//! Generated by `cargo djinn` (Verus backend). TRUSTED: do not edit.\n//! Regenerated from the specification on every `cargo djinn verify`.\n";

/// `relations.rs`: every declaration's precondition and relation as `open
/// spec fn`s over the mathematical views (`Seq`, `int`).
pub fn relations_rs(cx: &EmitCx, decls: &[Lowered]) -> String {
    relations_rs_with(cx, decls, &[])
}

/// `relations.rs` with the translations of the ambient functions the
/// constraints call (`ambient_verus`), which the relations refer to.
pub fn relations_rs_with(cx: &EmitCx, decls: &[Lowered], ambient: &[crate::ambient_verus::Translated]) -> String {
    let mut s = String::new();
    s.push_str(HEADER);
    s.push_str("//!\n//! Every Rust parameter appears here in its mathematical view: sequences\n//! as `Seq`, machine integers compared through `as int`. The implementation\n//! types reappear only in the stubs of the mirrored specification modules.\n");
    s.push_str("#![allow(unused_imports, unused_variables, unused_parens, non_snake_case, dead_code, non_camel_case_types)]\nuse vstd::prelude::*;\nuse crate::vocab::*;\n\nverus! {\n\n");
    if !ambient.is_empty() {
        s.push_str("// ---- ambient functions (translated; checked against the functions themselves\n// in the mirrored specification modules)\n\n");
        for a in ambient {
            s.push_str(&a.spec_fn);
            s.push('\n');
        }
    }
    // the structural equalities of the user types holding sequences, each once
    let mut seen: Vec<&str> = Vec::new();
    let helpers: Vec<&(String, String)> = decls.iter().flat_map(|d| d.helpers.iter()).filter(|(n, _)| if seen.contains(&n.as_str()) { false } else { seen.push(n); true }).collect();
    if !helpers.is_empty() {
        s.push_str("// ---- structural equality of the user types that hold sequences (`==` on two such Rust\n// values says nothing about their views; the relations compare contents)\n\n");
        for (_, text) in helpers {
            s.push_str(text);
            s.push('\n');
        }
    }
    // the user types compared by contents (`djinn_eq_T` exists)
    let eq_names: Vec<String> = decls.iter().flat_map(|d| d.helpers.iter().map(|(n, _)| n.clone())).collect();
    let has_eq = |t: &str| eq_names.iter().any(|n| *n == eq_fn_name(t.rsplit("::").next().unwrap_or(t)));
    for d in decls {
        s.push_str(&format!("// ---- {} {}\n\n", d.kind.word(), d.name));
        let ins = binders(&d.inputs, cx.names);
        s.push_str(&format!("pub open spec fn {}_pre({}) -> bool {{\n    {}\n}}\n\n", d.name, ins.join(", "), conj_lines(&d.pre)));
        let pre_app = format!("{}_pre({})", d.name, arg_names(&d.inputs).join(", "));
        let body = d.spec.join(" &&\n    ");
        let recursive = !d.decreases.is_empty();
        let body = if recursive {
            // the precondition, spelled out, as a hypothesis for the termination check
            format!("{pre_app} &&\n    ({} ==>\n    {body})", if d.pre.is_empty() { "true".to_string() } else { format!("({})", d.pre.join(" && ")) })
        } else if d.spec.is_empty() {
            pre_app.clone()
        } else {
            format!("{pre_app} &&\n    {body}")
        };
        // a choice function is, as in Lean, a function of its arguments'
        // contents: content-equal arguments give equal results (without it a
        // `spec_fn` over a struct holding a `Vec` could tell apart two values
        // `djinn_eq` makes equal, and `unambiguous` would be unprovable)
        let respects: Vec<String> = d.choices.iter().filter_map(|(c, t)| choice_respects(c, t, &has_eq)).collect();
        let body = if respects.is_empty() { body } else { format!("{body} &&\n    {}", respects.join(" &&\n    ")) };
        let rel = if d.choices.is_empty() { "spec" } else { "body" };
        let mut params = ins.clone();
        params.extend(choice_binders(&d.choices));
        params.extend(binders(&d.outputs, cx.names));
        let decreases = if recursive { format!("\n    decreases {}", d.decreases.join(", ")) } else { String::new() };
        s.push_str(&format!("pub open spec fn {}_{rel}({}) -> bool{decreases}\n{{\n    {}\n}}\n\n", d.name, params.join(", "), body));
        if !d.choices.is_empty() {
            let mut args = arg_names(&d.inputs);
            args.extend(choice_names(&d.choices));
            args.extend(arg_names(&d.outputs));
            let mut params = ins.clone();
            params.extend(binders(&d.outputs, cx.names));
            s.push_str(&format!(
                "/// `{}` is weakly specified: the implementer chooses {} — each a function of\n/// the inputs and of the `for` variables around its statement (or call site).\npub open spec fn {}_spec({}) -> bool {{\n    {}\n}}\n\n",
                d.name,
                d.choices.iter().map(|(n, _)| format!("`{n}`")).collect::<Vec<_>>().join(", "),
                d.name,
                params.join(", "),
                quant("exists", &d.choices, &format!("{}_body({})", d.name, args.join(", ")), &[])
            ));
        }
        // the conclusions of the declaration's proof obligations (`obligations.rs`)
        for o in obligations(cx, d).iter().filter(|o| o.how == How::Proof) {
            s.push_str(&o.post_fn());
            s.push('\n');
        }
    }
    s.push_str("} // verus!\n");
    s
}

/// One obligation of a declaration.
pub struct Obligation {
    /// `f.unambiguous`, `f.ens_0`, `f.wf`, `f.exists`, `f.impl_correct`: the
    /// report's name.
    pub name: String,
    /// The Verus function that carries it: `f_unambiguous`, …; for
    /// `impl_correct` the stub `f` itself.
    pub fn_name: String,
    pub doc: String,
    /// The proof fn's parameters (`x: i32, …`), requires and ensures. The
    /// `ensures` are the conjuncts of the conclusion; the proof fn states them
    /// as the one term `post_app()`, defined by `post_fn()` in `relations.rs`.
    pub params: String,
    pub requires: Vec<String>,
    pub ensures: Vec<String>,
    /// How it is discharged: a proof the implementer writes, the
    /// implementation itself (`impl_correct`), or derived by the generator.
    pub how: How,
}

impl Obligation {
    /// The name of the `spec fn` defining the obligation's conclusion:
    /// `f_unambiguous_post`, `f_wf_post`, ….
    pub fn post_name(&self) -> String {
        format!("{}_post", self.fn_name)
    }

    /// The conclusion as the proof fn states it: `f_wf_post(x, y, r)`.
    pub fn post_app(&self) -> String {
        format!("{}({})", self.post_name(), call_args(self))
    }

    /// The definition of the conclusion, for `relations.rs`: `pub open spec
    /// fn f_wf_post(params) -> bool { ensures_0 && ensures_1 && … }`.
    pub fn post_fn(&self) -> String {
        let body = match self.ensures.len() {
            0 => "true".to_string(),
            1 => self.ensures[0].clone(),
            _ => self.ensures.iter().map(|e| format!("({e})")).collect::<Vec<_>>().join(" &&\n    "),
        };
        format!("/// The conclusion of `{}` (`obligations.rs`): what its proof fn ensures, which this\n/// definition unfolds to.\npub open spec fn {}({}) -> bool {{\n    {body}\n}}\n", self.name, self.post_name(), self.params)
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum How {
    Proof,
    Impl,
    Derived,
}

/// A name for an output copy that no input has.
fn fresh(base: &str, taken: &[String]) -> String {
    let mut n = base.to_string();
    while taken.contains(&n) {
        n = format!("{n}_djinn");
    }
    n
}

pub fn obligations(cx: &EmitCx, d: &Lowered) -> Vec<Obligation> {
    let mut v = Vec::new();
    let ins = binders(&d.inputs, cx.names);
    let in_names = arg_names(&d.inputs);
    let out_names = arg_names(&d.outputs);
    let spec = format!("{}_spec", d.name);
    let pre = format!("{}_pre", d.name);
    let body = if d.choices.is_empty() { spec.clone() } else { format!("{}_body", d.name) };
    let ch_binders = choice_binders(&d.choices);
    let ch_names = choice_names(&d.choices);
    let taken: Vec<String> = in_names.iter().cloned().chain(ch_names.iter().cloned()).collect();
    // `_body(ins, choices, outs)`, or `_spec(ins, outs)` without choices
    let app = |outs: &[String]| {
        let mut a = in_names.clone();
        a.extend(ch_names.iter().cloned());
        a.extend(outs.iter().cloned());
        format!("{body}({})", a.join(", "))
    };
    let join = |parts: Vec<Vec<String>>| parts.into_iter().flatten().collect::<Vec<_>>().join(", ");

    if d.kind == Kind::Func {
        let single = d.outputs.len() == 1;
        let o1: Vec<(String, RType)> = d.outputs.iter().enumerate().map(|(i, (_, t))| (fresh(&if single { "o1".into() } else { format!("o{i}_1") }, &taken), t.clone())).collect();
        let o2: Vec<(String, RType)> = d.outputs.iter().enumerate().map(|(i, (_, t))| (fresh(&if single { "o2".into() } else { format!("o{i}_2") }, &taken), t.clone())).collect();
        // outputs of a user type holding sequences are equal when their
        // contents are (`djinn_eq_T`, one of the lowering's helpers), as the
        // relation itself compares them
        let structural = |t: &RType| needs_eq_with(t, &|n| d.helpers.iter().any(|(h, _)| *h == eq_fn_name(n)));
        let eqs: Vec<String> = o1.iter().zip(&o2).map(|((a, t), (b, _))| eq_term(a, b, t, cx.names, &structural)).collect();
        let doc = if d.choices.is_empty() {
            "GUARANTEE: for fixed inputs, any two outputs satisfying the relation are\n/// equal — the declaration denotes a (partial) function. Ambiguity inherited\n/// from mentioned rels must be resolved here.".to_string()
        } else {
            format!(
                "GUARANTEE: unambiguous MODULO the implementer's choices ({}): for fixed\n/// inputs and fixed choices, any two outputs satisfying `_body` are equal —\n/// two outputs may differ only because a choice differs.",
                d.choices.iter().map(|(n, _)| format!("`{n}`")).collect::<Vec<_>>().join(", ")
            )
        };
        v.push(Obligation {
            name: format!("{}.unambiguous", d.name),
            fn_name: format!("{}_unambiguous", d.name),
            doc,
            params: join(vec![ins.clone(), ch_binders.clone(), binders(&o1, cx.names), binders(&o2, cx.names)]),
            requires: vec![app(&arg_names(&o1)), app(&arg_names(&o2))],
            ensures: eqs,
            how: How::Proof,
        });
    }
    for (i, e) in d.ensures.iter().enumerate() {
        v.push(Obligation {
            name: format!("{}.ens_{i}", d.name),
            fn_name: format!("{}_ens_{i}", d.name),
            doc: format!("GUARANTEE: `ensures` clause {i} follows from the relation itself."),
            params: join(vec![ins.clone(), binders(&d.outputs, cx.names)]),
            requires: vec![format!("{spec}({})", join(vec![in_names.clone(), out_names.clone()]))],
            ensures: vec![e.clone()],
            how: How::Proof,
        });
    }
    if !d.wf.is_empty() {
        v.push(Obligation {
            name: format!("{}.wf", d.name),
            fn_name: format!("{}_wf", d.name),
            doc: "GUARANTEE: well-formedness and call sites — every partial operation is in\n/// its domain and every callee's precondition holds, wherever its side matters.".into(),
            params: join(vec![ins.clone(), ch_binders.clone(), binders(&d.outputs, cx.names)]),
            requires: vec![app(&out_names)],
            ensures: d.wf.clone(),
            how: How::Proof,
        });
    }
    if d.kind == Kind::Func && cx.impl_names.contains_key(&d.name) {
        v.push(Obligation {
            name: format!("{}.impl_correct", d.name),
            fn_name: d.name.clone(),
            doc: "GUARANTEE: the implementation meets the relation, TERMINATES and NEVER\n/// PANICS, unconditionally on the precondition domain: Verus verifies this stub,\n/// whose contract is the relation and whose body is the solution's function.".into(),
            params: String::new(),
            requires: vec![],
            ensures: vec![],
            how: How::Impl,
        });
        v.push(Obligation {
            name: format!("{}.exists", d.name),
            fn_name: String::new(),
            doc: "Existence for a func follows from `impl_correct`: a verified Verus function\n/// terminates and returns an output in the relation for every input admitted by\n/// the precondition (the implementer owes nothing).".into(),
            params: String::new(),
            requires: vec![],
            ensures: vec![],
            how: How::Derived,
        });
    } else if d.total {
        let ex = if d.outputs.is_empty() { format!("{spec}({})", in_names.join(", ")) } else { quant("exists", &d.outputs.iter().map(|(n, t)| (verus_ident(n), view_type(t, cx.names))).collect::<Vec<_>>(), &format!("{spec}({})", join(vec![in_names.clone(), out_names.clone()])), &[]) };
        v.push(Obligation {
            name: format!("{}.exists", d.name),
            fn_name: format!("{}_exists", d.name),
            doc: "GUARANTEE: realizability — for every input satisfying the preconditions,\n/// at least one output satisfies the relation.".into(),
            params: ins.join(", "),
            requires: vec![format!("{pre}({})", in_names.join(", "))],
            ensures: vec![ex],
            how: How::Proof,
        });
    }
    v
}

/// The short names an obligation may have.
pub fn is_obligation_kind(ob: &str) -> bool {
    crate::emit::is_obligation_kind(ob)
}

/// A proof obligation's signature: `pub proof fn NAME(params)\n    requires …\n
/// ensures NAME_post(args),` — the conclusion as the one term `relations.rs`
/// defines (`Obligation::post_fn`), the same in the pinned wrapper and in the
/// skeleton's stub.
fn signature(o: &Obligation) -> String {
    let mut s = format!("pub proof fn {}({})", o.fn_name, o.params);
    if !o.requires.is_empty() {
        s.push_str("\n    requires\n");
        for r in &o.requires {
            s.push_str(&format!("        {},\n", r.replace('\n', "\n        ")));
        }
    }
    s.push_str(if o.requires.is_empty() { "\n    ensures\n" } else { "    ensures\n" });
    s.push_str(&format!("        {},\n", o.post_app()));
    s
}

/// The call of the implementer's function with the obligation's parameters:
/// the names before each top-level `:` (a `spec_fn(A, B) -> C` type holds
/// commas of its own).
fn call_args(o: &Obligation) -> String {
    let mut names = Vec::new();
    let mut depth = 0i32;
    let mut cur = String::new();
    let mut prev = ' ';
    for c in o.params.chars() {
        match c {
            '(' | '<' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            '>' if prev != '-' => depth -= 1,
            ',' if depth == 0 => {
                names.push(std::mem::take(&mut cur));
                continue;
            }
            _ => {}
        }
        prev = c;
        cur.push(c);
    }
    if !cur.trim().is_empty() {
        names.push(cur);
    }
    names.iter().map(|p| p.split(':').next().unwrap_or("").trim().to_string()).filter(|n| !n.is_empty()).collect::<Vec<_>>().join(", ")
}

/// `obligations.rs`: every proof obligation, pinned, taking its proof from
/// `crate::proofs` by name.
pub fn obligations_rs(cx: &EmitCx, decls: &[Lowered]) -> String {
    let mut s = String::new();
    s.push_str(HEADER);
    s.push_str("//!\n//! Each `proof fn` below is PINNED by its contract and takes its proof from\n//! `crate::proofs` by name: its body calls the implementer's function of the\n//! same name, so Verus checks that the implementer's `requires` follow from the\n//! pinned ones and that the pinned `ensures` follow from the implementer's.\n//! The implementer may prove it any way, with any helpers, but cannot weaken it.\n");
    s.push_str("#![allow(unused_imports, unused_variables, unused_parens, non_snake_case, dead_code)]\nuse vstd::prelude::*;\nuse crate::relations::*;\nuse crate::vocab::*;\n\nverus! {\n\n");
    for d in decls {
        s.push_str(&format!("// ---- {}  ({}{})\n\n", d.name, d.kind.word(), if d.total { ", total" } else { "" }));
        for o in obligations(cx, d) {
            match o.how {
                How::Proof => {
                    // the body only transfers the implementer's conclusion; a large
                    // statement (many quantified items) can still take Z3 a while
                    s.push_str(&format!("/// {}\n#[verifier::rlimit(200)]\n{}{{\n    crate::proofs::{}({});\n}}\n\n", o.doc, signature(&o), o.fn_name, call_args(&o)));
                }
                How::Impl => {
                    s.push_str(&format!("// {}: the stub `{}` of the mirrored specification module carries this obligation.\n\n", o.name, cx.impl_names.get(&d.name).cloned().unwrap_or_default()));
                }
                How::Derived => {
                    s.push_str(&format!("// {}: derived from `{}.impl_correct`.\n\n", o.name, d.name));
                }
            }
        }
    }
    s.push_str("} // verus!\n");
    s
}

/// The implementation stub of a `fn` for the mirrored specification module:
/// the `fn` with the relation as its contract, delegating to the solution.
/// `None` for a `rel`, or a `fn` without an implementation (its stub would
/// have nothing to call).
pub fn impl_stub(cx: &EmitCx, d: &Lowered) -> Option<String> {
    if d.kind != Kind::Func || !cx.impl_names.contains_key(&d.name) {
        return None;
    }
    let is_mut = |n: &str| d.outputs.iter().any(|(o, _)| o == n);
    let ret = d.outputs.iter().find(|(n, _)| !d.impl_params.iter().any(|(p, _)| p == n));
    // a `&T` parameter is `&T` here too (the solution, compiled by the real
    // crate, takes it so); in the contract a shared reference is its value
    let params: Vec<String> = d.impl_params.iter().map(|(n, t)| format!("{}: {}{}", verus_ident(n), if is_mut(n) { "&mut " } else if d.impl_shared.contains(n) { "&" } else { "" }, exec_type(t, cx.names))).collect();
    // a `&mut v` parameter is `old(v)` on entry and `final(v)` on exit in a
    // contract, each of type `&mut T`: viewed by `@` (a sequence, a map) as it
    // stands, dereferenced (`*old(v)`) for a value whose view is a `match` or
    // the value itself
    let mut_term = |f: &str, n: &str, t: &RType| match t {
        RType::Seq(..) | RType::Map(..) => view_term(&format!("{f}({})", verus_ident(n)), t, cx.names),
        _ => view_term(&format!("*{f}({})", verus_ident(n)), t, cx.names),
    };
    let in_views: Vec<String> = d
        .impl_params
        .iter()
        .map(|(n, t)| if is_mut(n) { mut_term("old", n, t) } else if d.impl_shared.contains(n) { view_term(&format!("(*{})", verus_ident(n)), t, cx.names) } else { view_term(&verus_ident(n), t, cx.names) })
        .collect();
    let mut out_views: Vec<String> = Vec::new();
    if let Some((n, t)) = ret {
        out_views.push(view_term(&verus_ident(n), t, cx.names));
    }
    for (n, t) in &d.impl_params {
        if is_mut(n) {
            out_views.push(mut_term("final", n, t));
        }
    }
    let ret_s = match ret {
        Some((n, t)) => format!(" -> ({}: {})", verus_ident(n), exec_type(t, cx.names)),
        None => String::new(),
    };
    let mut all = in_views.clone();
    all.extend(out_views);
    Some(format!(
        "/// GUARANTEE (`{0}.impl_correct`): the implementation meets the relation, TERMINATES\n/// and NEVER PANICS on the precondition domain. Verus verifies this stub; its body\n/// is the solution's `{0}`, whatever that function states for itself.\n#[verifier::rlimit(200)]\npub fn {0}({1}){2}\n    requires\n        crate::relations::{0}_pre({3}),\n    ensures\n        crate::relations::{0}_spec({4}),\n{{\n    crate::solution::{0}({5})\n}}\n",
        d.name,
        params.join(", "),
        ret_s,
        in_views.join(", "),
        all.join(", "),
        arg_names(&d.impl_params).join(", ")
    ))
}

/// A `fn` without an implementation yet: a note in its place.
pub fn missing_stub(d: &Lowered) -> String {
    format!("// `{0}` is not implemented yet: `crate::solution::{0}` does not exist, so there is no stub\n// to verify (implement it, and the next `verify` writes the stub and its contract here).\n", d.name)
}

/// The skeleton's text for one proof obligation: the signature and a body
/// that does not verify.
pub fn stub_text(o: &Obligation) -> String {
    format!("{}{{\n    {TODO}\n}}\n\n", signature(o))
}

/// Does `text` hold the skeleton's stub of this obligation, untouched?
pub fn untouched_stub(text: &str, o: &Obligation) -> Option<std::ops::Range<usize>> {
    let stub = stub_text(o);
    text.find(&stub).map(|i| i..i + stub.len())
}

pub fn proofs_skeleton(cx: &EmitCx, decls: &[Lowered]) -> String {
    let mut s = String::new();
    s.push_str("//! The implementer's file. Written once by `cargo djinn translate`, never\n//! overwritten. Fill in every `proof fn` (replace the TODO marker with a proof);\n//! add any helper lemmas you need in this file, or in modules under `proofs/`\n//! (`mod helper;` here loads `proofs/helper.rs`).\n");
    s.push_str("#![allow(unused_imports, unused_variables, unused_parens, non_snake_case, dead_code)]\nuse vstd::prelude::*;\nuse crate::relations::*;\nuse crate::vocab::*;\n\nverus! {\n\n");
    for d in decls {
        let obs: Vec<Obligation> = obligations(cx, d).into_iter().filter(|o| o.how == How::Proof).collect();
        if obs.is_empty() {
            continue;
        }
        s.push_str(&format!("// ---- {}\n\n", d.name));
        for o in obs {
            s.push_str(&stub_text(&o));
        }
    }
    s.push_str(END_MARKER);
    s
}

/// The last line of the skeleton; new stubs are inserted before it.
pub const END_MARKER: &str = "} // verus!\n";

/// `vocab.rs`: the helpers the relations use.
pub fn vocab_rs() -> String {
    format!(
        "{HEADER}//!\n//! The vocabulary the relations use: a count, a sum, the first and last\n//! elements, adjacency (for `windows(2)`), `trig`, the explicit trigger\n//! of quantifiers that offer no term of their own (a quantified fact over `i`\n//! triggered on `trig(i)` is instantiated at `i0` by `assert(trig(i0))`),\n//! `bytes` (the view of a string), and the bit-level definitions with their\n//! lemmas.\n\
#![allow(unused_imports, dead_code)]\nuse vstd::prelude::*;\n\nverus! {{\n\n\
/// Always true: a trigger for quantifiers whose body offers none.\npub open spec fn trig<A>(x: A) -> bool {{\n    true\n}}\n\n\
/// The number of occurrences of `x` in `s`.\npub open spec fn count<A>(s: Seq<A>, x: A) -> int {{\n    s.filter(|y: A| y == x).len() as int\n}}\n\n\
/// The sum of a sequence of integers.\npub open spec fn sum(s: Seq<int>) -> int\n    decreases s.len(),\n{{\n    if s.len() == 0 {{ 0 }} else {{ sum(s.drop_last()) + s.last() }}\n}}\n\n\
/// `s.first()`.\npub open spec fn first<A>(s: Seq<A>) -> Option<A> {{\n    if s.len() > 0 {{ Option::Some(s[0]) }} else {{ Option::None }}\n}}\n\n\
/// `s.last()`.\npub open spec fn last<A>(s: Seq<A>) -> Option<A> {{\n    if s.len() > 0 {{ Option::Some(s[s.len() - 1]) }} else {{ Option::None }}\n}}\n\n\
/// `a` immediately followed by `b` somewhere in `s` (the pairs `windows(2)` visits).\npub open spec fn adjacent<A>(s: Seq<A>, a: A, b: A) -> bool {{\n    exists|k: int| #![trigger s[k]] 0 <= k && k + 1 < s.len() && s[k] == a && s[k + 1] == b\n}}\n\n\
/// `s[a..b]`: `s.subrange(a, b)` when `0 <= a <= b <= s.len()`, and the elements of `s` whose\n/// index is in `[a, b)` otherwise (vstd's `subrange` alone is specified only within range).\n/// The two backends agree wherever `0 <= a <= b <= s.len()`, which the well-formedness guard\n/// of every slice requires. So `slice(s, 0, n) == t` with `t.len() == n` says `n <= s.len()`.\npub open spec fn slice<A>(s: Seq<A>, a: int, b: int) -> Seq<A> {{\n    let lo = if a < 0 {{ 0int }} else if a > s.len() {{ s.len() as int }} else {{ a }};\n    let hi = if b < lo {{ lo }} else if b > s.len() {{ s.len() as int }} else {{ b }};\n    s.subrange(lo, hi)\n}}\n\n\
{VOCAB_EQ}{VOCAB_STRINGS}{VOCAB_BITS}{bit_lemmas}\
}} // verus!\n",
        bit_lemmas = bit_lemmas()
    )
}

/// `bit_and`/`bit_or`/`bit_xor` agree with Verus's `&`, `|`, `^` on each
/// unsigned machine type: proved here (Verus checks `vocab.rs` like any
/// file), for the implementer to call.
fn bit_lemmas() -> String {
    let mut s = String::from("// ---- the definitions agree with Verus's operators on machine integers\n\n");
    for t in ["u8", "u16", "u32", "u64"] {
        s.push_str(&format!(
            "/// `bit_and` is `&` on `{t}`.\npub proof fn lemma_bit_and_{t}(a: {t}, b: {t})\n    ensures\n        bit_and(a as nat, b as nat) == (a & b) as nat,\n    decreases a,\n{{\n    if a == 0 || b == 0 {{\n        assert((a & b) == 0) by (bit_vector)\n            requires a == 0 || b == 0;\n    }} else {{\n        assert((a >> 1{t}) == a / 2 && (b >> 1{t}) == b / 2) by (bit_vector);\n        assert((a & b) == (((a >> 1{t}) & (b >> 1{t})) * 2) + ((a % 2) * (b % 2))) by (bit_vector);\n        lemma_bit_and_{t}(a >> 1{t}, b >> 1{t});\n    }}\n}}\n\n\
/// `bit_or` is `|` on `{t}`.\npub proof fn lemma_bit_or_{t}(a: {t}, b: {t})\n    ensures\n        bit_or(a as nat, b as nat) == (a | b) as nat,\n    decreases a + b,\n{{\n    if a == 0 && b == 0 {{\n        assert((a | b) == 0) by (bit_vector)\n            requires a == 0 && b == 0;\n    }} else {{\n        assert((a >> 1{t}) == a / 2 && (b >> 1{t}) == b / 2) by (bit_vector);\n        assert((a | b) == (((a >> 1{t}) | (b >> 1{t})) * 2) + (if a % 2 == 1 || b % 2 == 1 {{ 1{t} }} else {{ 0{t} }})) by (bit_vector);\n        lemma_bit_or_{t}(a >> 1{t}, b >> 1{t});\n    }}\n}}\n\n\
/// `bit_xor` is `^` on `{t}`.\npub proof fn lemma_bit_xor_{t}(a: {t}, b: {t})\n    ensures\n        bit_xor(a as nat, b as nat) == (a ^ b) as nat,\n    decreases a + b,\n{{\n    if a == 0 && b == 0 {{\n        assert((a ^ b) == 0) by (bit_vector)\n            requires a == 0 && b == 0;\n    }} else {{\n        assert((a >> 1{t}) == a / 2 && (b >> 1{t}) == b / 2) by (bit_vector);\n        assert((a ^ b) == (((a >> 1{t}) ^ (b >> 1{t})) * 2) + (if a % 2 != b % 2 {{ 1{t} }} else {{ 0{t} }})) by (bit_vector);\n        lemma_bit_xor_{t}(a >> 1{t}, b >> 1{t});\n    }}\n}}\n\n"
        ));
    }
    s
}

